C     A. Kramida 2026: the TRUE jj labels of the rotated columns, and
C     the key table that makes them readable.  Include after RCGPAR.F,
C     which supplies KMX, KS and KC.  No IMPLICIT here, so this can go
C     into any routine.
C
C       NJJST(1..4,c,i)  N1, LEVEL OF j-**N1, N2, LEVEL OF j+**N2 FOR
C                        SUBSHELL i OF COLUMN c.  NJJST(1,c,i) = -1
C                        WHERE THE COLUMN STILL CARRIES AN LS TERM --
C                        l=0, N<=1 OR N>=4l+1, WHERE THE TWO BASES
C                        COINCIDE (SEE LSJJRT).  FILLED BY LSJJRT.
C       FIDJ2(c)         THE PRINTED LABEL OF COLUMN c.  FILLED BY
C                        LSJJID, KEYED BY LSJJKP AT THE END OF THE RUN.
C
C     THE LABEL.  A jj BASIS STATE IS, FOR EVERY SUBSHELL, ITS jj STATE
C     AND ITS OWN J, PLUS THE CHAIN OF INTERMEDIATE J's THAT COUPLES
C     THEM.  SPELT OUT THAT WILL NOT COME NEAR THE EIGHT CHARACTERS THE
C     EIGENVECTOR FORMATS ALLOW -- ONE SUBSHELL OF p**4 ALONE READS
C     p-2(0) p+2(2) -- SO IT IS CODED, ONE CHARACTER PER QUANTITY, IN
C     THE ALPHABET OF LSJJCC.  EMPTY SUBSHELLS ARE LEFT OUT: THEY HAVE
C     ONE STATE, J=0, AND LEAVE THE RUNNING J WHERE IT WAS.  WITH n THE
C     NUMBER OF OCCUPIED SUBSHELLS, THE LAYOUT IS
C
C       n <= 3    Ai Ji  FOR EVERY SUBSHELL, AND Ki FOR THE SUBSHELLS
C                 BETWEEN THE FIRST AND THE LAST:
C                    n=1  A1 J1              2 characters
C                    n=2  A1 J1 A2 J2        4
C                    n=3  A1 J1 A2 J2 K2 A3 J3   7
C       n =  4    Ai Ji ONLY, THE CHAIN DROPPED     8
C       n >= 5    Ai ONLY, THE J's DROPPED          n
C
C     WHERE
C
C       Ai   THE jj STATE OF SUBSHELL i -- ITS (j-**N1 v1 J1,
C            j+**N2 v2 J2) -- KEYED BY LSJJKP PER CONFIGURATION AND
C            SUBSHELL
C       Ji   2 * THE TOTAL J OF SUBSHELL i, CODED DIRECTLY: CODE 1 IS
C            2J=0, CODE 2 IS 2J=1, AND SO ON
C       Ki   2 * THE RUNNING J AFTER COUPLING SUBSHELL i IN
C
C     THE FIRST AND LAST RUNNING J's ARE NEVER CODED BECAUSE THEY ARE
C     NEVER FREE: THE FIRST IS J1 AND THE LAST IS THE J OF THE BLOCK.
C     SO FOR n <= 3 -- WHICH IS ALMOST EVERY REAL CONFIGURATION -- THE
C     LABEL NAMES THE BASIS STATE COMPLETELY: WITHIN ONE CONFIGURATION
C     AND ONE J BLOCK, TWO COLUMNS WITH THE SAME LABEL ARE THE SAME
C     COLUMN.  ABOVE THAT THERE IS NO ROOM AND LSJJKP SAYS SO.
C
C     Ji IS KEPT OUT OF Ai, IN A CHARACTER OF ITS OWN, TO KEEP THE KEY
C     SHORT.  FOLDED IN, THE CODES OF ONE SUBSHELL WOULD RUN TO THE
C     NUMBER OF ITS LEVELS -- ABOUT 300 FOR f**6 -- INSTEAD OF THE
C     NUMBER OF ITS (N1 v1 J1, N2 v2 J2), WHICH PEAKS AT 70.
C
C     THE KEY.  CODES RUN PER (PARITY, CONFIGURATION, SUBSHELL) -- THE
C     CONFIGURATION INDEX RUNS WITHIN A PARITY, SO THE PARITY IS PART
C     OF THE SLOT -- AND THE SLOT OF CODE NC IS FIXED BY ARITHMETIC, SO
C     NOTHING IS SEARCHED BUT THE CODES OF ONE SUBSHELL:
C
C       KEYNC(I,JC,K)    CODES ISSUED SO FAR FOR THAT SUBSHELL
C       KEYDT(1..5,M)    l, THEN NJJST(1..4), OR -1 AND THE LS TERM
C                        INDEX WHERE THE SUBSHELL WAS NOT SPLIT
C       NKEYOV           LABEL POSITIONS THAT WANTED A CODE PAST
C                        KJJCOD; THEY CARRY '*' AND LSJJKP SAYS SO
C
C     KJJCOD IS THE SIZE OF THE CODE ALPHABET IN LSJJCC, AND SO ALSO
C     THE MOST CODES ONE SUBSHELL CAN HAVE.
      PARAMETER (KJJCOD=85, KJJKEY=2*KC*KS*KJJCOD)
      COMMON/LSJJLB/NJJST(4,KMX,KS)
      COMMON/LSJJKT/NKEYOV,KEYNC(KS,KC,2),KEYDT(5,KJJKEY)
      CHARACTER*8 FIDJ2
      COMMON/LSJJCH/FIDJ2(KMX)
