C     A. Kramida 2026: STATE OF THE RELATIVE-ENERGY (GROUP) FEATURE -
C     HETEROSCEDASTIC WEIGHTING OF THE EXPERIMENTAL LEVELS.
C
C     A GROUP IS A SET OF LEVELS KNOWN PRECISELY RELATIVE TO ONE
C     ANOTHER BUT TIED TO THE GROUND LEVEL ONLY LOOSELY - THE '+x'
C     SYSTEMS OF AN EXPERIMENTAL COMPILATION.  IT IS NAMED BY A LETTER
C     IN COLUMN 14 OF A LEVEL RECORD OF 'RCEINP': THE UPPERCASE LETTER
C     ON ITS BASE, THE LOWERCASE ONE ON EVERY OTHER MEMBER.  THE TWO
C     STANDARD DEVIATIONS OF THE GROUP COME FROM A CARD BLOCK AT THE
C     END OF 'RCEINP'.  GROUP G IS THE G-TH LETTER OF THE ALPHABET
C     THROUGHOUT, SO THE 26 ARRAYS BELOW ARE INDEXED BY THE LETTER
C     ITSELF AND NEED NO LOOKUP.
C
C       IGRP(K,M) - 0 IF LEVEL K OF BLOCK M CARRIES NO LETTER,
C                   +G IF IT IS THE BASE OF GROUP G, -G IF A MEMBER.
C                   DIMENSIONED AND ALLOCATED LIKE NF, WHOSE (K,M)
C                   SLOT IS A STABLE EXPERIMENTAL IDENTITY.
C       SIGG(G)   - SIGMA OF THE GROUP'S COMMON OFFSET (THE TIE TO THE
C                   GROUND LEVEL).  MEANINGLESS WHEN IUNT(G)=1.
C       SIGI(G)   - SIGMA OF THE INTERNAL (LEVEL-TO-LEVEL) ERROR.
C       WG(G),WI(G) - THE WEIGHTS DERIVED FROM THEM, SIG0**2/
C                   (SIG0**2+SIGMA**2).  SEE SUBROUTINE RELWT.
C       SIG0      - THE DEVIATION THE MODEL ITSELF ACHIEVES, TAKEN
C                   FROM THE PREVIOUS CYCLE'S STDEV, RATCHETED SO THAT
C                   IT NEVER GROWS.  SEE SUBROUTINE RELSIG.
C       IFRZ      - 1 ONCE SIG0 HAS SETTLED AND THE WEIGHTS ARE HELD.
C       TWF(K,M)  - THE RESIDUAL THAT ACTUALLY FEEDS D: TW FOR A LEVEL
C                   WITH NO LETTER, TW-TW(BASE) FOR A MEMBER, EACH
C                   MULTIPLIED BY SQRT OF ITS WEIGHT.  SEPARATE FROM TW
C                   BECAUSE TW IS WRITTEN TO 'RCEOUT' AND GATES THE
C                   OUTPUT OF A HIGH-LYING LEVEL, SO IT MUST NOT BE
C                   SCALED OR ZEROED.
C       KMIDX(K,M)- THE ROW OF V THAT BELONGS TO LEVEL SLOT (K,M).
C                   INTEGER*4: THE ROW COUNT EXCEEDS 32767.
C       KB(G),MB(G) - LEVEL AND BLOCK INDICES OF THE GROUP'S BASE.
C       NGMEM(G)  - NUMBER OF MEMBERS (LOWERCASE RECORDS) OF GROUP G.
C       NGLEV(G)  - NUMBER OF LEVEL RECORDS CARRYING THE LETTER AT ALL,
C                   BASE INCLUDED.
C       IUNT(G)   - 1 IF THE GROUP HAS NO MEASURED TIE TO THE GROUND
C                   LEVEL (BLANK SIGMA_BASE FIELD): ITS BASE THEN
C                   CONTRIBUTES NO RESIDUAL.
C       ICRD(G)   - 1 IF A GROUP CARD WAS SUPPLIED FOR THE LETTER.
C       NREL      - NUMBER OF GROUPS IN USE.  NREL=0 SWITCHES EVERY
C                   NEW PATH OFF, WHICH IS EVERY DECK WRITTEN BEFORE
C                   THIS FEATURE EXISTED.
C
      INTEGER*2 IGRP
      INTEGER*4 KMIDX
      COMMON/CREL/ IGRP_PTR,TWF_PTR,KMIDX_PTR,SIGG(26),SIGI(26),
     1  WG(26),WI(26),SIG0,
     2  KB(26),MB(26),NGMEM(26),NGLEV(26),IUNT(26),ICRD(26),NREL,IFRZ
      INTEGER*8 IGRP_PTR,TWF_PTR,KMIDX_PTR
      DIMENSION IGRP(IA,IX),TWF(IA,IX),KMIDX(IA,IX)
      POINTER (IGRP_PTR,IGRP),(TWF_PTR,TWF),(KMIDX_PTR,KMIDX)
