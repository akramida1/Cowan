C     A. Kramida 2026: THE TRUE jj TRAILER OF TAPE2E, AS HELD IN MEMORY.
C
C     RCG APPENDS THE TRAILER TO TAPE2E WHEN COLUMN 38 OF ITS MAIN
C     CONTROL CARD - KCPLD(8) - IS 8.  IT COMES AFTER EVERYTHING RCE
C     HAS EVER READ FROM UNIT 2, SO A FILE THAT CARRIES IT IS STILL AN
C     ORDINARY TAPE2E; RDJJ2E FINDS IT BY READING ON PAST THE LAST CSET
C     UNTIL THE MAGIC RECORD.  LAYOUT AND MEANING: SEE LABEL 850 OF
C     RCEINP IN rcg11kd.f AND LSJJ/README.txt.
C
C       IJJON  - 1 IF A TRAILER WAS FOUND AND READ, 0 OTHERWISE
C       IJJCS  - 1 IF THE TRAILER BLOCKS OF THE CSET NOW IN MEMORY HAVE
C                BEEN IDENTIFIED (MJJ IS THEN VALID), 0 OTHERWISE
C       NBKJ2  - NUMBER OF J BLOCKS IN THE TRAILER (ALL CSETS)
C       NJJJ2  - 2*J OF EACH TRAILER BLOCK
C       NLSJ2  - MATRIX SIZE OF EACH TRAILER BLOCK
C       IOKJ2  - 0 IF THE ROTATION FAILED FOR THAT BLOCK, 1 OTHERWISE
C       LOFJ2  - OFFSET OF THE BLOCK'S FIRST LABEL IN YJJ
C       IBAJ   - INDEX OF THE BLOCK'S PACKED MATRIX IN BUFJ (SEE WR1)
C       MJJ(M) - TRAILER BLOCK HOLDING J MATRIX M OF THE CURRENT CSET
C       BUFJ   - THE TRANSFORMATION MATRICES, PK1-PACKED AS BUFA IS
C       YJJ    - THE EIGHT-CHARACTER TRUE jj LABELS, BLOCK AFTER BLOCK
C
      INTEGER*8 BUFJ_PTR,YJJ_PTR
      COMMON/JJ2E/ BUFJ_PTR,YJJ_PTR,IJJON,IJJCS,NBKJ2,MAXBJU,JOFFS,
     1  IBAJ(NBJJX),NJJJ2(NBJJX),NLSJ2(NBJJX),IOKJ2(NBJJX),
     2  LOFJ2(NBJJX),MJJ(IX)
      CHARACTER*12 BUFJ
      CHARACTER*8 YJJ
      POINTER (BUFJ_PTR,BUFJ(1))
      POINTER (YJJ_PTR,YJJ(1))
